export default function AsciiAnimation() {
  const [currentFrame, setCurrentFrame] = useState(0);

  useEffect(() => {
    const interval = setInterval(() => {
      setCurrentFrame((prev) => (prev + 1) % frames.length);
    }, 32); // Change frame every 32ms for 2.6 Hz frequency

    return () => clearInterval(interval);
  }, []);

  return (
    <div
      className="w-full h-full flex items-center justify-center font-mono text-xs text-muted-foreground whitespace-pre"
      style={{ fontSize: 'clamp(8px, 2vw, 12px)' }} // Responsive font size
    >
      {frames[currentFrame]}
    </div>
  );
}